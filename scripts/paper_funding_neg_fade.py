def mode_audit() -> None:
    positions = load_existing_positions()
    if not positions:
        print("no positions recorded")
        return
    closed = [p for p in positions if p.get("status") == "closed"]
    open_pos = [p for p in positions if p.get("status") == "open"]
    print(f"=== paper funding_neg_fade audit ===")
    print(f"  total: {len(positions)}  closed: {len(closed)}  open: {len(open_pos)}")

    if closed:
        pnls = np.array([p.get("net_pnl_usd", 0) for p in closed])
        wins = pnls[pnls > 0]
        losses = pnls[pnls <= 0]
        cum = pnls.sum()
        pf = (wins.sum() / abs(losses.sum())) if len(losses) and losses.sum() != 0 else 999
        print(f"  cum PnL: ${cum:+.2f}  WR: {(len(wins)/len(pnls)*100):.1f}%  PF: {pf:.2f}")
        print(f"  avg win: ${wins.mean():+.2f}  avg loss: ${losses.mean():+.2f}  max win: ${wins.max():+.2f}  max loss: ${losses.min():+.2f}")

    by_sym: dict[str, list[dict]] = {}
    for p in closed:
        by_sym.setdefault(p.get("symbol", "?"), []).append(p)
    for sym, plist in sorted(by_sym.items()):
        spnls = np.array([p["net_pnl_usd"] for p in plist])
        swins = spnls[spnls > 0]
        slosses = spnls[spnls <= 0]
        pf = (swins.sum() / abs(slosses.sum())) if len(slosses) and slosses.sum() != 0 else 999
        print(f"  {sym:6s} ({PER_ASSET_POLICY[sym]['bucket']:9s}) n={len(plist):3d}  cum=${spnls.sum():+.2f}  WR={(len(swins)/len(spnls)*100):.1f}%  PF={pf:.2f}")

    by_reason: dict[str, int] = {}
    for p in closed:
        by_reason[p.get("exit_reason", "?")] = by_reason.get(p.get("exit_reason", "?"), 0) + 1
    print(f"  exits: {by_reason}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["analyze", "paper", "live", "live_trading", "testnet_trading", "audit", "kill_switch", "arm_live"], default="paper")
    ap.add_argument("--arm-testnet", action="store_true",
                    help="actually submit orders in testnet_trading mode "
                         "(without it the mode prints intents and stops)")
    ap.add_argument("--symbol", action="append", help="restrict to symbol (repeatable)")
    args = ap.parse_args()
    if args.mode == "analyze":
        mode_analyze()
    elif args.mode == "paper":
        mode_paper(args.symbol)
    elif args.mode == "live":
        mode_live(args.symbol)
    elif args.mode == "live_trading":
        mode_live_trading()
    elif args.mode == "testnet_trading":
        mode_testnet_trading(arm=args.arm_testnet)
    elif args.mode == "kill_switch":
        KILL_SWITCH_PATH.parent.mkdir(parents=True, exist_ok=True)
        KILL_SWITCH_PATH.touch()
        print(f"kill switch ACTIVATED: {KILL_SWITCH_PATH}")
        print("live mode will refuse on next tick. rm the file to resume.")
    elif args.mode == "arm_live":
        # Set LIVE_TRADING_ENABLED = True in this file (surgical edit)
        text = Path(__file__).read_text(encoding="utf-8")
        if "LIVE_TRADING_ENABLED = True" in text:
            print("LIVE_TRADING_ENABLED already True")
        else:
            new = text.replace("LIVE_TRADING_ENABLED = False", "LIVE_TRADING_ENABLED = True", 1)
            Path(__file__).write_text(new, encoding="utf-8")
            print("LIVE_TRADING_ENABLED flipped to True. Edit-and-restart required to take effect in this process; next cron tick will use the new value.")
    elif args.mode == "audit":
        mode_audit()


if __name__ == "__main__":
    main()
