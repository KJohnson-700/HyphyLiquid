def mode_analyze() -> None:
    """Re-run the detail backtest and print per-symbol observed stats.
    Updates PER_ASSET_POLICY based on observed MAE p10 and MFE p50 * R."""
    print(f"=== analyze: detailed funding_neg_fade backtest (1%/1% TP/SL, max_hold=24h) ===\n")
    updated_policy = {}
    for sym in ALL_SYMBOLS:
        try:
            df, label = load_hl_with_funding(sym)
        except Exception as e:
            print(f"  {sym}: FAILED to load: {e}")
            continue
        n_neg_fund = int((df["funding_actual"] < NEG_THRESHOLD).sum())
        # Use the detail backtest
        from backtest_funding_neg_fade_detail import detailed_backtest, score_detail  # type: ignore
        trades = detailed_backtest(df)
        s = score_detail(trades)
        if not s:
            print(f"  {sym}: no trades")
            continue
        # Per user profile: stop from observed MAE (use p10 for conservative), TP from MFE * R
        # Use med MAE (less conservative) for sizing the typical case
        new_stop = max(0.005, abs(s["mae_p10"]) / 100)  # p10 MAE (percent -> fraction)
        new_tp = min(0.03, (s["mfe_p50"] / 100) * R_MULTIPLE)  # MFE p50 * R, capped at 3%
        new_hold = max(1, int(s["hold_med"]))
        prev = PER_ASSET_POLICY[sym]
        updated_policy[sym] = {
            "bucket": prev["bucket"],
            "stop_pct": round(new_stop, 4),
            "tp_pct": round(new_tp, 4),
            "max_hold_h": new_hold,
            "obs_n": s["n"],
            "obs_pf": round(s["pf"], 2),
            "obs_wr": round(s["wr"], 1),
            "obs_med_pct": round(s["med"], 4),
            "obs_mae_p10": round(s["mae_p10"], 4),
            "obs_mfe_p50": round(s["mfe_p50"], 4),
        }
        print(f"--- {sym} ---")
        print(f"  n={s['n']} WR={s['wr']:.1f}% PF={s['pf']:.2f} med={s['med']:+.4f}% net={s['net_pct_total']:+.4f}%")
        print(f"  observed MAE: med={s['mae_med']:.4f}% p10={s['mae_p10']:.4f}% worst={s['mae_worst']:.4f}%")
        print(f"  observed MFE: med={s['mfe_p50']:.4f}% p90={s['mfe_p90']:.4f}% max={s['mfe_max']:.4f}%")
        print(f"  observed hold: med={s['hold_med']:.0f}h p90={s['hold_p90']:.0f}h")
        print(f"  -> proposed stop={new_stop:.4f}  tp={new_tp:.4f}  max_hold={new_hold}h")
        print()

    if updated_policy:
        # Write policy update
        pol_path = PROJECT_ROOT / "data" / "strategy_search" / "paper_funding_neg_fade_policy.json"
        pol_path.write_text(json.dumps(updated_policy, indent=2, default=str))
        print(f"policy updated -> {pol_path}")


