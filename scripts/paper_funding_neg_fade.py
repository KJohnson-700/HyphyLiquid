# Mode: live — process new bars since last run (cron-friendly)
# -----------------------------------------------------------------------------

def _process_bars(
    sym: str,
    policy: dict,
    df: pd.DataFrame,
    start_idx: int,
    open_pos: PaperPosition | None,
    consec_loss: int,
    halt_until: dict,
    cum_pnl: float,
    daily_pnl: dict,
) -> tuple[PaperPosition | None, int, float, float, float]:
    """Process bars from start_idx. Returns (open_pos, consec_loss, cum_pnl, total_funding, total_price)."""
    closes = df["close"].values
    highs = df["high"].values
    lows = df["low"].values
    funds = df["funding_actual"].values
    times = df.index

    stop_pct = policy["stop_pct"]
    tp_pct = policy["tp_pct"]
    max_hold = policy["max_hold_h"]
    risk_usd = RISK_PER_TRADE_USD
    notional_usd = min(risk_usd / stop_pct, BANKROLL * 10)
    cost_usd_per_trade = (COST_BPS_ROUND_TRIP / 10_000.0) * notional_usd

    pos = open_pos
    in_trade = pos is not None
    if in_trade:
        # Reconstruct in-trade state from the existing pos
        entry_price = pos.entry_price
        # Default: assume position was opened before start_idx (most common case)
        # Use 0 so hold_bars >= max_hold fires immediately for stale positions
        entry_idx = 0
        # Try to find the actual entry index in the panel via searchsorted
        try:
            entry_dt = pd.Timestamp(pos.entry_ts)
            # If tz-naive, localize to UTC; if tz-aware, convert
            if entry_dt.tzinfo is None:
                if times.tz is not None:
                    entry_dt = entry_dt.tz_localize(times.tz)
            else:
                if times.tz is not None:
                    entry_dt = entry_dt.tz_convert(times.tz)
            # Search in the FULL bar series, not the new_bars slice
            entry_idx = times.searchsorted(entry_dt)[0] if hasattr(times, "searchsorted") else 0
            entry_idx = max(0, entry_idx)
        except Exception:
            entry_idx = 0
        cur_mae = pos.mae_pct / 100.0
        cur_mfe = pos.mfe_pct / 100.0
        funding_collected = pos.funding_collected_usd
    else:
        entry_price = 0.0
        entry_idx = 0
        cur_mae = 0.0
        cur_mfe = 0.0
        funding_collected = 0.0

    sig = signal_funding_neg_fade(df, funding_col="funding_actual", neg_threshold=NEG_THRESHOLD)

    for i in range(start_idx, len(df)):
        ts_iso = str(times[i])
        ts_date = str(times[i].date())

        # Consec loss halt
        if sym in halt_until and ts_iso < halt_until[sym]:
            if in_trade:
                net_pnl_usd, _ = _close_position(
                    pos=pos, exit_price=closes[i], exit_reason="halt_force_close",
                    cur_mae=cur_mae, cur_mfe=cur_mfe, hold_bars=i - entry_idx,
                    funding_collected=funding_collected, cost_usd_per_trade=cost_usd_per_trade,
                    ts_iso=ts_iso, ts_date=ts_date,
                )
                cum_pnl += net_pnl_usd
                daily_pnl[ts_date] = daily_pnl.get(ts_date, 0) + net_pnl_usd
                print(f"  [{sym} {policy['bucket']}] CLOSED halt_force_close: net=${net_pnl_usd:+.2f} (cum=${cum_pnl:+.2f})")
                in_trade = False
                pos = None
            continue

        # Daily loss breaker
        if daily_pnl.get(ts_date, 0) <= -BANKROLL * DAILY_LOSS_LIMIT_PCT:
            if in_trade:
                net_pnl_usd, _ = _close_position(
                    pos=pos, exit_price=closes[i], exit_reason="daily_loss_breaker",
                    cur_mae=cur_mae, cur_mfe=cur_mfe, hold_bars=i - entry_idx,
                    funding_collected=funding_collected, cost_usd_per_trade=cost_usd_per_trade,
                    ts_iso=ts_iso, ts_date=ts_date,
                )
                cum_pnl += net_pnl_usd
                daily_pnl[ts_date] = daily_pnl.get(ts_date, 0) + net_pnl_usd
                print(f"  [{sym} {policy['bucket']}] CLOSED daily_loss_breaker: net=${net_pnl_usd:+.2f} (cum=${cum_pnl:+.2f})")
                in_trade = False
                pos = None
            continue

        if not in_trade:
            if sig.iloc[i] == 1 and i + 1 < len(df):
                decision_id = gen_id()
                paper_id = paper_trade_id(sym, times[i])
                if paper_id_exists(paper_id):
                    pass  # already in JSONL, skip
                else:
                    in_trade = True
                    entry_price = closes[i]
                    entry_idx = i
                    cur_mae = 0.0
                    cur_mfe = 0.0
                    funding_collected = 0.0
                    pos = PaperPosition(
                        symbol=sym,
                        bucket=policy["bucket"],
                        side="long",
                        entry_ts=ts_iso,
                        entry_price=float(entry_price),
                        entry_funding=float(funds[i]),
                        notional_usd=float(notional_usd),
                        stop_pct=float(stop_pct),
                        tp_pct=float(tp_pct),
                        max_hold_h=int(max_hold),
                        risk_usd=float(risk_usd),
                        decision_id=decision_id,
                        paper_id=paper_id,
                        status="open",
                    )
        else:
            bar_mae = (lows[i] - entry_price) / entry_price
            bar_mfe = (highs[i] - entry_price) / entry_price
            cur_mae = min(cur_mae, bar_mae)
            cur_mfe = max(cur_mfe, bar_mfe)
            if funds[i] < 0:
                funding_collected += abs(funds[i]) * pos.notional_usd

            hold_bars = i - entry_idx
            tp_price = entry_price * (1 + tp_pct)
            sl_price = entry_price * (1 - stop_pct)

            exit_now = False
            exit_reason = ""
            exit_price = closes[i]

            if lows[i] <= sl_price:
                exit_now = True
                exit_reason = "stop_loss"
                exit_price = sl_price
            elif highs[i] >= tp_price:
                exit_now = True
                exit_reason = "take_profit"
                exit_price = tp_price
            elif hold_bars >= max_hold:
                exit_now = True
                exit_reason = "max_hold"

            if exit_now:
                net_pnl_usd, is_loss = _close_position(
                    pos=pos, exit_price=exit_price, exit_reason=exit_reason,
                    cur_mae=cur_mae, cur_mfe=cur_mfe, hold_bars=hold_bars,
                    funding_collected=funding_collected, cost_usd_per_trade=cost_usd_per_trade,
                    ts_iso=ts_iso, ts_date=ts_date,
                )
                cum_pnl += net_pnl_usd
                daily_pnl[ts_date] = daily_pnl.get(ts_date, 0) + net_pnl_usd
                if is_loss:
                    consec_loss += 1
                    if consec_loss >= CONSEC_LOSS_HALT:
                        halt_until[sym] = (times[i] + pd.Timedelta(hours=24)).isoformat()
                        print(f"  [{sym}] consec loss halt: {consec_loss} losses, halt until {halt_until[sym]}")
                        consec_loss = 0
                else:
                    consec_loss = 0
                print(f"  [{sym} {policy['bucket']}] CLOSED {exit_reason}: entry={pos.entry_price:.2f} exit={exit_price:.2f}  net=${net_pnl_usd:+.2f} (cum=${cum_pnl:+.2f})  hold={hold_bars}h  fund=${funding_collected:+.4f}")
                in_trade = False
                pos = None

    # If still in trade at end, save it as an open position
    if in_trade and pos is not None:
        # update MAE/MFE/funding on the live pos object
        pos.mae_pct = float(cur_mae * 100)
        pos.mfe_pct = float(cur_mfe * 100)
        pos.funding_collected_usd = float(funding_collected)
        pos.hold_bars = int(len(df) - 1 - entry_idx)
        # Don't write to JSONL yet — keep in state file
    elif in_trade is False and pos is None:
        pos = None  # explicit

    return pos, consec_loss, cum_pnl, halt_until.get(sym, ""), daily_pnl.get(str(times[-1].date()), 0.0)


def mode_live(symbol_filter: list[str] | None = None) -> None:
    """Process new bars since last run. Cron-friendly: idempotent, appends only new positions."""
    syms = symbol_filter or ALL_SYMBOLS
    state = load_state()
    last_processed = state.get("last_processed_ts", {})
    open_positions = state.get("open_positions", {})

    print(f"=== paper: LIVE mode (process new bars) ===")
    print(f"  bankroll: ${BANKROLL:.0f}  risk/trade: ${RISK_PER_TRADE_USD:.0f}")
    print(f"  state file: {STATE_PATH}")
    print(f"  last_processed_ts: {last_processed}")
    if open_positions:
        print(f"  open positions:")
        for s, p in open_positions.items():
            if p is None:
                print(f"    {s}: (none)")
            else:
                print(f"    {s}: entry={p.get('entry_price')} hold={p.get('hold_bars')}h status={p.get('status')}")
    print()

    new_state = {"last_processed_ts": dict(last_processed), "open_positions": {}}

    for sym in syms:
        try:
            df, label = load_hl_with_funding(sym)
        except Exception as e:
            print(f"  {sym}: load failed: {e}")
            continue
        if sym not in PER_ASSET_POLICY:
            # No calibrated stop/tp for this symbol yet. Skip rather than
            # crash the whole run — ALL_SYMBOLS includes research names
            # that have never been calibrated, and an uncalibrated symbol
            # must not be paper-traded at a guessed size.
            print(f"  {sym}: no PER_ASSET_POLICY entry, skipping")
            continue
        policy = PER_ASSET_POLICY[sym]

        last_ts_str = last_processed.get(sym)
        if last_ts_str:
            try:
                last_ts = pd.Timestamp(last_ts_str)
                if last_ts.tzinfo is not None:
                    last_ts = last_ts.tz_localize(None)
                # Find index of first bar AFTER last_ts
                if df.index.tzinfo is not None:
                    start_idx = df.index.tz_localize(None).get_indexer([last_ts], method="bfill")[0] + 1
                else:
                    start_idx = df.index.get_indexer([last_ts], method="bfill")[0] + 1
                if start_idx < 0 or start_idx >= len(df):
                    start_idx = max(0, start_idx)
            except Exception as e:
                print(f"  {sym}: state parse failed ({e}), starting from 0")
                start_idx = 0
        else:
            start_idx = 0

        if start_idx >= len(df):
            print(f"  {sym}: no new bars (last_ts={last_ts_str})")
            new_state["last_processed_ts"][sym] = str(df.index[-1])
            new_state["open_positions"][sym] = open_positions.get(sym)  # preserve
            continue

        print(f"  {sym}: processing {len(df) - start_idx} new bars (from {df.index[start_idx]})")

        # Reconstruct open position
        open_pos = None
        if sym in open_positions and open_positions[sym] is not None and open_positions[sym].get("status") == "open":
            try:
                p = open_positions[sym]
                open_pos = PaperPosition(**p)
            except Exception as e:
                print(f"  {sym}: failed to restore open position: {e}")
                open_pos = None

        # Per-symbol state for this run
        consec_loss = 0
        halt_until: dict = {}
        cum_pnl = 0.0  # local to this run
        daily_pnl: dict = {}

        pos, consec_loss, cum_pnl, halt_ts, _ = _process_bars(
            sym=sym, policy=policy, df=df, start_idx=start_idx,
            open_pos=open_pos, consec_loss=consec_loss, halt_until=halt_until,
            cum_pnl=cum_pnl, daily_pnl=daily_pnl,
        )

        # Update state
        new_state["last_processed_ts"][sym] = str(df.index[-1])
        if pos is not None:
            new_state["open_positions"][sym] = asdict(pos)
            print(f"  {sym}: position still open (entry={pos.entry_price}, hold={pos.hold_bars}h)")
        else:
            new_state["open_positions"][sym] = None
        if sym in halt_until:
            new_state.setdefault("halt_until", {})[sym] = halt_until[sym]

    save_state(new_state)
    print(f"\nstate updated -> {STATE_PATH}")
    print(f"  last_processed_ts: {new_state['last_processed_ts']}")
    open_count = sum(1 for v in new_state["open_positions"].values() if v is not None)
    print(f"  open positions: {open_count}")


