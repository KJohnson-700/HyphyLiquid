def load_existing_positions() -> list[dict]:
    if not POSITIONS_PATH.exists():
        return []
    out = []
    with POSITIONS_PATH.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return out


def append_position(pos: dict) -> None:
    with POSITIONS_PATH.open("a", encoding="utf-8") as f:
        f.write(json.dumps(pos, default=str) + "\n")


