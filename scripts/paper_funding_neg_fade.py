def _live_trading_guard_ok() -> tuple[bool, str]:
    """Three guard checks before any real order can be placed."""
    if not LIVE_TRADING_ENABLED:
        return False, "LIVE_TRADING_ENABLED is False; flip the flag in scripts/paper_funding_neg_fade.py"
    if not TESTNET_PROOF_PATH.exists():
        return False, f"missing testnet proof at {TESTNET_PROOF_PATH}"
    try:
        proof = json.loads(TESTNET_PROOF_PATH.read_text(encoding="utf-8"))
    except Exception as e:
        return False, f"failed to parse testnet proof: {e}"
    if proof.get("status") != "bracket_proof_passed":
        return False, f"testnet proof status is {proof.get('status')!r}, expected 'bracket_proof_passed'"
    if proof.get("protective_stop_visible") is not True:
        return False, "testnet proof did not show protective_stop_visible=True"
    return True, "ok"


# -----------------------------------------------------------------------------
# Safety infrastructure (added 2026-08-22)
# -----------------------------------------------------------------------------
# Runtime kill switch:
#   touch data/live_kill_switch.flag  -> halt live trading immediately
#   rm data/live_kill_switch.flag     -> resume (still subject to all other guards)
# Consec-loss / drawdown state persists across ticks in data/live_funding_neg_fade_state.json
# so the 3-loss halt and 40% drawdown kill survive process restarts.
# Heartbeat: data/live_heartbeat.txt is rewritten every run; stale = cron died.
# Circuit log: data/live_circuit_log.jsonl is append-only for post-mortem.

def _kill_switch_active() -> bool:
    return KILL_SWITCH_PATH.exists()


def _load_live_state(path=None, bankroll: float | None = None) -> dict:
    """Load persisted trading state. Returns safe defaults if missing.

    path/bankroll default to the mainnet file and bankroll; testnet passes its
    own so a testnet run can never inherit or clobber mainnet circuit state.
    """
    path = path or LIVE_STATE_PATH
    if path.exists():
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except Exception as e:
            print(f"  WARN: state parse failed ({e}); starting fresh")
    return {
        "consecutive_losses": 0,
        "last_loss_ts": None,
        "last_win_ts": None,
        "peak_equity_usd": LIVE_BANKROLL_USD if bankroll is None else bankroll,
        "halted_until": None,
        "stopped": False,
        "total_pnl_usd": 0.0,
        "trade_count": 0,
    }


def _save_live_state(state: dict, path=None) -> None:
    path = path or LIVE_STATE_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(state, indent=2, sort_keys=True), encoding="utf-8")


def _log_circuit_event(event: str, **fields) -> None:
    """Append a circuit event to the post-mortem log."""
    LIVE_CIRCUIT_LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    rec = {"ts_utc": pd.Timestamp.utcnow().isoformat(), "event": event, **fields}
    with LIVE_CIRCUIT_LOG_PATH.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(rec) + "\n")


def _check_live_circuits(state: dict, current_equity_usd: float) -> tuple[bool, str]:
    """Decide whether new orders are allowed. Returns (allowed, reason)."""
    # Hard kill: file flag
    if _kill_switch_active():
        return False, f"runtime kill switch present at {KILL_SWITCH_PATH}; rm to resume"
    # Hard kill: state.stopped (set by drawdown)
    if state.get("stopped"):
        return False, "state.stopped=True (drawdown kill tripped); reset state to resume"
    # Consec-loss threshold: defense in depth — if counter is at the halt
    # threshold but halted_until is unset (e.g. state was loaded but not
    # updated, or file was hand-edited), still refuse. _record_trade_outcome
    # also sets halted_until, but the threshold alone is sufficient.
    consec = int(state.get("consecutive_losses") or 0)
    if consec >= LIVE_CONSEC_LOSS_HALT:
        return False, f"consec_losses={consec} >= {LIVE_CONSEC_LOSS_HALT}; reset data/live_funding_neg_fade_state.json to resume"
    # 24h halt from consec losses
    halted_until = state.get("halted_until")
    if halted_until:
        try:
            halt_ts = pd.Timestamp(halted_until)
            now = pd.Timestamp.utcnow()
            if now < halt_ts:
                return False, f"halted until {halt_ts.isoformat()} (consec-loss pause)"
        except Exception:
            pass
    # Drawdown kill (40% of starting bankroll)
    peak = max(float(state.get("peak_equity_usd") or LIVE_BANKROLL_USD), current_equity_usd)
    if current_equity_usd < LIVE_BANKROLL_USD * (1 - LIVE_DRAWDOWN_KILL_PCT):
        state["stopped"] = True
        _save_live_state(state)
        _log_circuit_event("drawdown_kill", equity=current_equity_usd, peak=peak)
        return False, f"drawdown kill: equity ${current_equity_usd:.2f} <= ${LIVE_BANKROLL_USD * (1 - LIVE_DRAWDOWN_KILL_PCT):.2f}"
    return True, "ok"


def _record_trade_outcome(state: dict, pnl_usd: float) -> None:
    """Update persisted state after a closed trade. Stops on 3 consec losses."""
    now_iso = pd.Timestamp.utcnow().isoformat()
    state["trade_count"] = int(state.get("trade_count") or 0) + 1
    state["total_pnl_usd"] = float(state.get("total_pnl_usd") or 0.0) + pnl_usd
    if pnl_usd < 0:
        state["consecutive_losses"] = int(state.get("consecutive_losses") or 0) + 1
        state["last_loss_ts"] = now_iso
        if state["consecutive_losses"] >= LIVE_CONSEC_LOSS_HALT:
            state["halted_until"] = (pd.Timestamp.utcnow() + pd.Timedelta(hours=24)).isoformat()
            _log_circuit_event(
                "consec_loss_halt",
                consecutive_losses=state["consecutive_losses"],
                halted_until=state["halted_until"],
                trade_pnl_usd=pnl_usd,
            )
    else:
        state["consecutive_losses"] = 0
        state["last_win_ts"] = now_iso
    _save_live_state(state)


def _reconcile_on_chain(info, user: str, local_open_keys: set[str]) -> list[dict]:
    """Fetch exchange state and log any drift vs local view. Best-effort."""
