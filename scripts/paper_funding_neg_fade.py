    for ap in positions:
        pos = (ap or {}).get("position") or {}
        coin = pos.get("coin")
        szi = float(pos.get("szi", 0))
        if szi == 0 or coin is None:
            continue
        on_chain_positions.append({"coin": coin, "szi": szi, "entryPx": pos.get("entryPx")})
