def _funding_during_hold(sym: str, entry_ts_iso: str, exit_ts_iso: str, notional_usd: float = 1000.0) -> float:
    """Estimate funding collected between entry and exit.

    Reads asset_ctx JSONL files for the symbol, sums (funding_actual * notional)
    over the bars whose timestamp falls in [entry_ts, exit_ts]. For longs, a
    negative funding rate means longs receive. Same convention as the paper mode.

    Args:
        sym: Trading symbol (e.g., "HYPE", "BTC")
        entry_ts_iso: ISO timestamp of position entry
        exit_ts_iso: ISO timestamp of position exit
        notional_usd: Position notional in USD (required for accurate P&L)

    Returns: Funding collected in USD, or 0.0 if data is missing.
    """
    if notional_usd <= 0:
        return 0.0
    try:
        # Force UTC-aware to match the +00:00 timestamps in asset_ctx files
        entry_dt = pd.Timestamp(entry_ts_iso)
        if entry_dt.tz is None:
            entry_dt = entry_dt.tz_localize("UTC")
        exit_dt = pd.Timestamp(exit_ts_iso)
        if exit_dt.tz is None:
            exit_dt = exit_dt.tz_localize("UTC")
    except Exception:
        return 0.0
    # Asset ctx files are {symbol}_{date}.jsonl; for HIP-3 the filename uses
    # an underscore in place of the colon (xyz_gold_2026-08-22.jsonl).
    fn_sym = sym.lower().replace(":", "_")
    asset_dir = PROJECT_ROOT / "data" / "asset_ctx"
    if not asset_dir.exists():
        return 0.0
    # Find all matching files
    matches = sorted(asset_dir.glob(f"{fn_sym}_*.jsonl"))
    total_collected = 0.0
    for f in matches:
        try:
            with f.open(encoding="utf-8") as fh:
                for line in fh:
                    try:
                        rec = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    poll_ts = _parse_iso(rec.get("poll_ts"))
                    if poll_ts is None:
                        continue
                    # Normalize to UTC-aware
                    if poll_ts.tz is None:
                        poll_ts = poll_ts.tz_localize("UTC")
                    if poll_ts < entry_dt or poll_ts > exit_dt:
                        continue
                    ctx = rec.get("context") or {}
                    fund = float(ctx.get("funding") or 0.0)
                    if fund < 0:
                        # Funding rate is per-hour. Multiply rate * notional to get USD.
                        total_collected += abs(fund) * notional_usd
        except OSError:
            continue
    return total_collected


def _detect_and_record_live_closes(info, user: str, state: dict) -> int:
    """Reconcile local open positions vs on-chain user_state. Append closes
    to LIVE_POSITIONS_PATH and update state (total_pnl_usd, consec_losses,
    peak_equity). Returns the number of closes recorded."""
    open_local = _load_live_open_positions()
    if not open_local:
        return 0

    try:
        on_chain = info.user_state(user) or {}
    except Exception as e:
        _log_circuit_event("live_close_detect_failed", error=str(e))
        return 0
    asset_positions = on_chain.get("assetPositions") or []
    on_chain_keys: set[tuple[str, str]] = set()
    on_chain_marks: dict[str, float] = {}
    for ap in asset_positions:
        pos = (ap or {}).get("position") or {}
        coin = pos.get("coin")
        szi = float(pos.get("szi", 0))
        if szi == 0 or coin is None:
            continue
        # We only track longs (LIVE_SYMBOLS is long-only); treat any non-zero
        # szi as "open" for our local key.
        on_chain_keys.add((coin, "long"))
        # markPx is not directly in user_state; leave empty for now, the
        # caller can fetch via meta if needed.

    LIVE_POSITIONS_PATH.parent.mkdir(parents=True, exist_ok=True)
    still_open: list[dict] = []
    closes_recorded = 0
    pnl_delta = 0.0
    is_loss_streak = []
    for pos in open_local:
        sym = pos.get("symbol")
        if (sym, "long") in on_chain_keys:
            still_open.append(pos)
            continue
        # Position closed between ticks
        entry_px = float(pos.get("entry_px", 0))
        notional = float(pos.get("notional_usd", 0))
        size_coin = float(pos.get("size_coin", 0))
        # Fetch exit price from live mark. If unavailable, log warning and
        # mark exit_reason to indicate P&L may be incomplete.
        exit_px = None
        exit_price_available = False
        try:
            ctx_resp = info.meta_and_asset_ctxs() or {}
            for tup in ctx_resp or []:
                if not isinstance(tup, (list, tuple)) or len(tup) < 2:
                    continue
                universe = tup[0] or []
                ctxs = tup[1] or []
                for u, c in zip(universe, ctxs):
                    if u.get("name") == sym:
                        m = float((c or {}).get("markPx") or 0)
                        if m > 0:
                            exit_px = m
                            exit_price_available = True
                        break
        except Exception as e:
            print(f"  WARN: failed to fetch exit price for {sym}: {e}")
        if not exit_price_available:
            print(f"  WARN: no exit price for {sym}, P&L will be funding-only")
            exit_px = entry_px  # Fallback but log indicates incomplete

        # Compute P&L
        price_pnl_usd = (exit_px - entry_px) / entry_px * notional if entry_px > 0 else 0.0
        # Funding estimate: sum the funding in USD [entry_ts, now]
        entry_ts = pos.get("entry_ts") or pos.get("signal_ts") or ""
        now_iso = pd.Timestamp.utcnow().isoformat()
        funding_collected_usd = _funding_during_hold(sym, entry_ts, now_iso, notional)
        cost_usd = notional * 0.0008  # 8 bps round trip
        net_pnl_usd = price_pnl_usd - cost_usd + funding_collected_usd
        is_loss = net_pnl_usd < 0

        closed_record = {
            "paper_id": pos.get("paper_id"),
            "symbol": sym,
            "bucket": "v1",
            "side": "long",
            "entry_ts": entry_ts,
            "entry_price": entry_px,
            "entry_funding": pos.get("entry_funding", 0.0),
            "notional_usd": notional,
            "stop_pct": pos.get("stop_pct", 0.0),
            "tp_pct": pos.get("tp_pct", 0.0),
            "max_hold_h": pos.get("max_hold_h", 0),
            "risk_usd": pos.get("risk_usd", 0.0),
            "decision_id": pos.get("decision_id", ""),
            "status": "closed",
            "exit_ts": now_iso,
            "exit_price": exit_px,
            "exit_reason": "close_detected_via_user_state" + ("_no_exit_price" if not exit_price_available else ""),
            "mae_pct": 0.0,
            "mfe_pct": 0.0,
            "hold_bars": 0,
            "funding_collected_usd": float(funding_collected_usd),
            "price_pnl_usd": float(price_pnl_usd),
            "cost_usd": float(cost_usd),
            "net_pnl_usd": float(net_pnl_usd),
            "cum_pnl_usd": 0.0,  # recomputed below
            "notes": "auto-recorded by mode_live_trading close-detector",
        }
        # Idempotency: skip if this paper_id already in LIVE_POSITIONS_PATH
        existing_ids: set[str] = set()
        if LIVE_POSITIONS_PATH.exists():
            try:
                with LIVE_POSITIONS_PATH.open(encoding="utf-8") as fh:
                    for ln in fh:
                        try:
                            existing_ids.add(json.loads(ln).get("paper_id", ""))
                        except json.JSONDecodeError:
                            continue
            except OSError:
                pass
        if closed_record["paper_id"] in existing_ids:
            still_open.append(pos)  # keep tracking; will be removed by a re-detect
            continue
        with LIVE_POSITIONS_PATH.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(closed_record) + "\n")
        closes_recorded += 1
        pnl_delta += net_pnl_usd
        is_loss_streak.append(is_loss)
        _log_circuit_event(
            "live_close_recorded",
            symbol=sym,
            paper_id=closed_record["paper_id"],
            net_pnl_usd=net_pnl_usd,
            price_pnl_usd=price_pnl_usd,
            funding_collected_usd=funding_collected_usd,
        )

    # Persist updated open positions
    _save_live_open_positions(still_open)

    # Update state totals
    if closes_recorded:
        prev_total = float(state.get("total_pnl_usd") or 0.0)
        prev_count = int(state.get("trade_count") or 0)
        prev_consec = int(state.get("consecutive_losses") or 0)
        new_total = prev_total + pnl_delta
        new_count = prev_count + closes_recorded
        # Consec losses: if last close was a loss, increment from 0; if win, reset to 0
        last_was_loss = is_loss_streak[-1] if is_loss_streak else False
        new_consec = prev_consec + 1 if last_was_loss else 0
        peak = float(state.get("peak_equity_usd") or LIVE_BANKROLL_USD)
        new_equity = LIVE_BANKROLL_USD + new_total
        new_peak = max(peak, new_equity)
        state["total_pnl_usd"] = new_total
        state["trade_count"] = new_count
        state["consecutive_losses"] = new_consec
        state["peak_equity_usd"] = new_peak
        state["last_close_ts"] = pd.Timestamp.utcnow().isoformat()
        # Halt on 3 consec losses
        if new_consec >= LIVE_CONSEC_LOSS_HALT:
            halt_until = pd.Timestamp.utcnow() + pd.Timedelta(hours=24)
            state["halted_until"] = halt_until.isoformat()
            _log_circuit_event("live_halt_triggered", reason=f"consec_losses={new_consec}", halted_until=state["halted_until"])
        _save_live_state(state)
    return closes_recorded


def _parse_iso(s: str | None):
    """Local ISO parser to avoid pulling in extra deps."""
    if not s:
        return None
    try:
        if s.endswith("Z"):
            s = s[:-1] + "+00:00"
        return pd.Timestamp(s)
    except Exception:
        return None


def _cross_venue_snapshot(sym: str, hl_funding_at_signal: float | None) -> dict:
    """Best-effort snapshot of Binance funding for a symbol at signal time.

    Returns a dict with binance_sym, binance_funding_per_hour, delta, age_seconds.
    Used to annotate live order records so we can later measure whether
    cross-venue divergence correlates with trade outcomes. If no recent
    Binance data is available (record older than 30 min or file missing),
    returns just {available: False, reason: ...}.
    """
    try:
        from scripts.binance_delta import compute_delta
        info = compute_delta(sym, hl_funding_at_signal)
        return {
            "available": info.get("binance_funding_per_hour") is not None,
            "binance_sym": info.get("binance_sym"),
            "binance_funding_per_hour": info.get("binance_funding_per_hour"),
            "delta_per_hour": info.get("delta"),
            "boost_eligible": info.get("boost_eligible", False),
            "fetched_ts": info.get("fetched_ts"),
            "age_seconds": info.get("age_seconds"),
        }
    except Exception as e:
        return {"available": False, "reason": f"compute_delta failed: {e}"}



def _testnet_guard_ok() -> tuple[bool, str]:
    """Testnet execution is only allowed to reach testnet.

    Deliberately does NOT consult LIVE_TRADING_ENABLED -- no mainnet funds are
    involved, so gating this behind the mainnet flag would push people to flip
    that flag for testing, which is the opposite of safe. It requires instead
    that .env is actually pointed at testnet, so a box configured for mainnet
    cannot run this mode at all.
    """
    env = os.getenv("HYPERLIQUID_ENV", "").strip().lower()
    if env != "testnet":
        return False, (f"HYPERLIQUID_ENV is {env or 'unset'!r}, refusing: this mode "
                       f"only runs against testnet")
    if _kill_switch_active():
        return False, "kill switch is active"
    return True, "testnet guard passed"


def mode_live_trading() -> None:
    """Walk LIVE_SYMBOLS bars, build bracket intents, submit via OrderManager.

    Safety chain (all must pass):
      1. LIVE_TRADING_ENABLED (one-line flip in this file)
      2. testnet proof on disk with status=bracket_proof_passed
      3. runtime kill switch absent (data/live_kill_switch.flag)
      4. persisted state not stopped / not in halt window
      5. equity above 40% drawdown kill
      6. on-chain reconcile (logs drift; not a hard refuse)

    Off by default (LIVE_TRADING_ENABLED = False). Every order attempt is
    logged to LIVE_ORDERS_PATH. State persists in LIVE_STATE_PATH.
    """
    print("=== LIVE funding_neg_fade: real-order mode ===")
    print(f"  LIVE_TRADING_ENABLED = {LIVE_TRADING_ENABLED}")
    print(f"  LIVE_SYMBOLS         = {LIVE_SYMBOLS}")
    print(f"  LIVE_BANKROLL_USD    = ${LIVE_BANKROLL_USD:.0f}")
    print(f"  LIVE_RISK_USD        = ${LIVE_RISK_USD:.2f} per trade")
    print(f"  kill_switch          = {'ACTIVE' if _kill_switch_active() else 'clear'}")
    print()

    # Guard 1+2: code flag + testnet proof
    ok, reason = _live_trading_guard_ok()
    if not ok:
        print(f"  REFUSED: {reason}")
        _write_heartbeat("refused_guard", reason)
        return
    print(f"  guard 1+2 (code+testnet): {reason}")

    # Load persisted state
    state = _load_live_state()
    print(f"  state: consec_losses={state.get('consecutive_losses')} trade_count={state.get('trade_count')} total_pnl=${state.get('total_pnl_usd', 0):+.2f}")

    # Guard 3+4+5: kill switch, halt, drawdown
    current_equity = LIVE_BANKROLL_USD + float(state.get("total_pnl_usd") or 0.0)
    allowed, circuit_reason = _check_live_circuits(state, current_equity)
    if not allowed:
        print(f"  REFUSED: {circuit_reason}")
        _write_heartbeat("refused_circuit", circuit_reason)
        return
    print(f"  guard 3+4+5 (kill+halt+dd): {circuit_reason}")
    print()

    # Lazy import: OrderManager pulls in eth_account, hyperliquid SDK, etc.
    try:
        from src.execution.order_manager import (
            BracketOrderIntent, OrderManager, OrderResult,
        )
    except Exception as e:
        print(f"  REFUSED: could not import OrderManager: {e}")
        _write_heartbeat("refused_import", str(e))
        return

    # Build SDK clients from .env
    try:
        from dotenv import load_dotenv
        load_dotenv(PROJECT_ROOT / ".env")
        from eth_account import Account
        from hyperliquid.exchange import Exchange
        from hyperliquid.info import Info
        from hyperliquid.utils import constants
        pk = os.getenv("HYPERLIQUID_PRIVATE_KEY", "").strip()
        user = os.getenv("HYPERLIQUID_WALLET_ADDRESS", "").strip()
        if not pk.startswith("0x"):
            pk = "0x" + pk
        wallet = Account.from_key(pk)
        env_url = constants.MAINNET_API_URL  # live = mainnet
        info = Info(env_url, skip_ws=True)
        exchange = Exchange(wallet, env_url)
    except Exception as e:
        print(f"  REFUSED: could not build SDK clients: {e}")
        _write_heartbeat("refused_sdk", str(e))
        return

    # Guard 6: on-chain reconciliation
    print(f"  on-chain reconcile:")
    for d in _reconcile_on_chain(info, user, set()):
        print(f"    {d.get('event')}: {d}")
        _log_circuit_event(d.get("event", "reconcile"), **{k: v for k, v in d.items() if k != "event"})

    # Close-detect: append any positions that closed since the last tick to
    # LIVE_POSITIONS_PATH and update state totals. Runs BEFORE new orders so
    # the dashboard sees closed P&L even on the tick that opens a new trade.
    closes = _detect_and_record_live_closes(info, user, state)
    if closes:
        print(f"  close-detect: recorded {closes} closed live position(s)")
        # Re-load state to pick up the updated totals
        state = _load_live_state()

    om = OrderManager(
        exchange=exchange,
        info=info,
        bankroll=LIVE_BANKROLL_USD,
        risk_per_trade_pct=LIVE_RISK_USD / LIVE_BANKROLL_USD,
        env="mainnet",
    )

    LIVE_ORDERS_PATH.parent.mkdir(parents=True, exist_ok=True)
    print(f"  order log: {LIVE_ORDERS_PATH}")
    print()

    for sym in LIVE_SYMBOLS:
        try:
            df, _ = load_hl_with_funding(sym)
        except Exception as e:
            print(f"  {sym}: load failed: {e}")
            continue
        if sym not in PER_ASSET_POLICY:
            # No calibrated stop/tp for this symbol yet. Skip rather than
            # crash the whole run — ALL_SYMBOLS includes research names
            # that have never been calibrated, and an uncalibrated symbol
            # must not be paper-traded at a guessed size.
            print(f"  {sym}: no PER_ASSET_POLICY entry, skipping")
            continue
        policy = PER_ASSET_POLICY[sym]
        sig = signal_funding_neg_fade(df, funding_col="funding_actual", neg_threshold=NEG_THRESHOLD)
        # Walk bars; collect bracket intents for the most recent unfired signal.
        # sig carries df's DatetimeIndex, so sig[i] would be a label lookup and
        # raise KeyError on an integer -- take the values positionally.
        sig_v = sig.to_numpy() if hasattr(sig, "to_numpy") else sig
        closes = df["close"].values
        times = df.index
        last_signal_idx = -1
        for i in range(1, len(df)):
            if sig_v[i] and not sig_v[i - 1] and closes[i] > 0:
                last_signal_idx = i
        if last_signal_idx < 0:
            print(f"  {sym}: no fresh signal in this run")
            continue

        i = last_signal_idx
        entry_px = float(closes[i])
        sl_px = entry_px * (1 - policy["stop_pct"])
        tp_px = entry_px * (1 + policy["tp_pct"])
        notional = LIVE_RISK_USD / max(policy["stop_pct"], 1e-6)
        intent = BracketOrderIntent(
            signal_ts=times[i],
            symbol=sym,
            side="long",
            entry_px=entry_px,
            sl_px=sl_px,
            tp_px=tp_px,
            notional_usd=notional,
            reason=f"funding_neg_fade live {sym} signal {times[i]}",
        )
        print(f"  {sym}: signal @ {times[i]} entry={entry_px} sl={sl_px} tp={tp_px} notional=${notional:.0f}")
        try:
            result: OrderResult = om.execute_bracket_intent(intent)
        except Exception as e:
            print(f"  {sym}: OrderManager crashed: {e}")
            result = None
        record = {
            "ts_utc": pd.Timestamp.utcnow().isoformat(),
            "symbol": sym,
            "intent": {
                "signal_ts": str(times[i]),
                "side": "long",
                "entry_px": entry_px,
                "sl_px": sl_px,
                "tp_px": tp_px,
                "notional_usd": notional,
            },
            "cross_venue": _cross_venue_snapshot(sym, float(df["funding_actual"].iloc[i]) if "funding_actual" in df.columns else None),
            "result": (None if result is None else {
                "filled": result.filled,
                "status": result.status,
                "entry_oid": result.entry_oid,
                "tp_oid": result.tp_oid,
                "sl_oid": result.sl_oid,
                "size_coin": result.size_coin,
                "risk_verdict": str(result.risk_verdict),
                "error": result.error,
            }),
        }
        with LIVE_ORDERS_PATH.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(record) + "\n")
        if result is None or not result.filled:
            print(f"  {sym}: not filled (status={None if result is None else result.status}, error={None if result is None else result.error})")
        else:
            print(f"  {sym}: FILLED entry_oid={result.entry_oid} size={result.size_coin}")
            # Persist this open position so the next tick's close-detector
            # can find it. Without this, the position would be invisible to
            # the dashboard's live_pnl_summary until a manual write.
            decision_id = record["intent"].get("signal_ts", "")
            paper_id = f"live-fnf-{sym}-{pd.Timestamp.utcnow().strftime('%Y%m%d%H%M%S')}-{result.entry_oid or 'x'}"
            open_pos = {
                "paper_id": paper_id,
                "symbol": sym,
                "side": "long",
                "entry_ts": record["ts_utc"],
                "entry_px": entry_px,
                "entry_funding": float(df["funding_actual"].iloc[i]) if "funding_actual" in df.columns else 0.0,
                "size_coin": float(result.size_coin or 0),
                "notional_usd": notional,
                "stop_pct": policy["stop_pct"],
                "tp_pct": policy["tp_pct"],
                "max_hold_h": policy["max_hold_h"],
                "risk_usd": LIVE_RISK_USD,
                "decision_id": str(decision_id),
                "entry_oid": result.entry_oid,
                "tp_oid": result.tp_oid,
                "sl_oid": result.sl_oid,
            }
            current_open = _load_live_open_positions()
            # If we already have an open for this symbol, replace it
            current_open = [p for p in current_open if p.get("symbol") != sym]
            current_open.append(open_pos)
            _save_live_open_positions(current_open)

    _write_heartbeat("ok", f"syms={','.join(LIVE_SYMBOLS)} consec={state.get('consecutive_losses')}")


