STATE_PATH = PROJECT_ROOT / "data" / "paper_funding_neg_fade_state.json"


def load_state() -> dict:
    if not STATE_PATH.exists():
        return {"last_processed_ts": {}, "open_positions": {}}
    try:
        return json.loads(STATE_PATH.read_text(encoding="utf-8"))
    except Exception:
        return {"last_processed_ts": {}, "open_positions": {}}


def save_state(state: dict) -> None:
    tmp = STATE_PATH.with_suffix(".tmp")
    tmp.write_text(json.dumps(state, indent=2, default=str), encoding="utf-8")
    tmp.replace(STATE_PATH)


def paper_id_exists(paper_id: str) -> bool:
    """Check if paper_id already exists in JSONL (for idempotency)."""
    if not POSITIONS_PATH.exists():
        return False
    with POSITIONS_PATH.open("r", encoding="utf-8") as f:
        for line in f:
            if paper_id in line:
                return True
    return False


def _close_position(
    pos: PaperPosition,
    exit_price: float,
    exit_reason: str,
    cur_mae: float,
    cur_mfe: float,
    hold_bars: int,
    funding_collected: float,
    cost_usd_per_trade: float,
    ts_iso: str,
    ts_date: str,
) -> tuple[float, bool]:
    """Close an open position, write to JSONL (idempotent on paper_id), return (net_pnl_usd, is_loss)."""
    # Idempotency: skip if this paper_id already has a record in JSONL
    if paper_id_exists(pos.paper_id):
        # Already closed in a prior run — return a fake zero P&L
        return 0.0, False

    price_pnl_usd = (exit_price - pos.entry_price) / pos.entry_price * pos.notional_usd
    net_pnl_usd = price_pnl_usd - cost_usd_per_trade + funding_collected

    pos.status = "closed"
    pos.exit_ts = ts_iso
    pos.exit_price = float(exit_price)
    pos.exit_reason = exit_reason
    pos.mae_pct = float(cur_mae * 100)
    pos.mfe_pct = float(cur_mfe * 100)
    pos.hold_bars = int(hold_bars)
    pos.funding_collected_usd = float(funding_collected)
    pos.price_pnl_usd = float(price_pnl_usd)
    pos.cost_usd = float(cost_usd_per_trade)
    pos.net_pnl_usd = float(net_pnl_usd)

    append_position(asdict(pos))
    return net_pnl_usd, net_pnl_usd < 0


def mode_paper(symbol_filter: list[str] | None = None) -> None:
    """Walk each symbol's funding panel, simulate paper trading."""
    syms = symbol_filter or ALL_SYMBOLS
    existing = load_existing_positions()
    existing_ids = {p.get("paper_id") for p in existing}
    cum_pnl = sum(p.get("net_pnl_usd", 0) for p in existing)
    daily_pnl: dict[str, float] = {}
    consec_loss = 0
    halt_until: dict[str, str] = {}  # sym -> halt_until_iso

    print(f"=== paper: walk funding panel ===")
    print(f"  bankroll: ${BANKROLL:.0f}  risk/trade: ${RISK_PER_TRADE_USD:.0f}  ({RISK_PER_TRADE_PCT*100:.0f}%)")
    print(f"  daily loss limit: ${BANKROLL*DAILY_LOSS_LIMIT_PCT:.0f}  consec halt: {CONSEC_LOSS_HALT}")
    print(f"  symbols: {syms}")
    print(f"  existing positions: {len(existing)}  cum_pnl: ${cum_pnl:+.2f}")
    print()

    for sym in syms:
        try:
            df, label = load_hl_with_funding(sym)
        except Exception as e:
            print(f"  {sym}: load failed: {e}")
            continue
        if sym not in PER_ASSET_POLICY:
            # No calibrated stop/tp for this symbol yet. Skip rather than
            # crash the whole run — ALL_SYMBOLS includes research names
            # that have never been calibrated, and an uncalibrated symbol
            # must not be paper-traded at a guessed size.
            print(f"  {sym}: no PER_ASSET_POLICY entry, skipping")
            continue
        policy = PER_ASSET_POLICY[sym]
        sig = signal_funding_neg_fade(df, funding_col="funding_actual", neg_threshold=NEG_THRESHOLD)
        closes = df["close"].values
        highs = df["high"].values
        lows = df["low"].values
        funds = df["funding_actual"].values
        times = df.index

        # Position sizing
        stop_pct = policy["stop_pct"]
        tp_pct = policy["tp_pct"]
        max_hold = policy["max_hold_h"]
        risk_usd = RISK_PER_TRADE_USD
        # notional = risk / stop
        notional_usd = min(risk_usd / stop_pct, BANKROLL * 10)  # 10x leverage cap
        # paper cost: round-trip
        cost_usd_per_trade = (COST_BPS_ROUND_TRIP / 10_000.0) * notional_usd

        # Walk
        in_trade = False
        pos: PaperPosition | None = None
        cur_mae = 0.0
        cur_mfe = 0.0
        funding_collected = 0.0

        for i in range(len(df)):
            ts_iso = str(times[i])
            ts_date = str(times[i].date())

            # Consec loss halt: if halted, force-close open position at market and skip new entries
            if sym in halt_until and ts_iso < halt_until[sym]:
                if in_trade:
                    net_pnl_usd, is_loss = _close_position(
                        pos=pos, exit_price=closes[i], exit_reason="halt_force_close",
                        cur_mae=cur_mae, cur_mfe=cur_mfe, hold_bars=i - entry_idx,
                        funding_collected=funding_collected, cost_usd_per_trade=cost_usd_per_trade,
                        ts_iso=ts_iso, ts_date=ts_date,
                    )
                    cum_pnl += net_pnl_usd
                    daily_pnl[ts_date] = daily_pnl.get(ts_date, 0) + net_pnl_usd
                    print(f"  [{sym} {policy['bucket']}] CLOSED halt_force_close: entry={pos.entry_price:.2f} exit={closes[i]:.2f}  net=${net_pnl_usd:+.2f} (cum=${cum_pnl:+.2f})  hold={i-entry_idx}h")
                    in_trade = False
                    pos = None
                continue

            # Daily loss breaker: if -3% for the day, force-close open position at market
            if daily_pnl.get(ts_date, 0) <= -BANKROLL * DAILY_LOSS_LIMIT_PCT:
                if in_trade:
                    net_pnl_usd, is_loss = _close_position(
                        pos=pos, exit_price=closes[i], exit_reason="daily_loss_breaker",
                        cur_mae=cur_mae, cur_mfe=cur_mfe, hold_bars=i - entry_idx,
                        funding_collected=funding_collected, cost_usd_per_trade=cost_usd_per_trade,
                        ts_iso=ts_iso, ts_date=ts_date,
                    )
                    cum_pnl += net_pnl_usd
                    daily_pnl[ts_date] = daily_pnl.get(ts_date, 0) + net_pnl_usd
                    print(f"  [{sym} {policy['bucket']}] CLOSED daily_loss_breaker: entry={pos.entry_price:.2f} exit={closes[i]:.2f}  net=${net_pnl_usd:+.2f} (cum=${cum_pnl:+.2f})  hold={i-entry_idx}h")
                    in_trade = False
                    pos = None
                continue

            if not in_trade:
                if sig.iloc[i] == 1 and i + 1 < len(df):
                    in_trade = True
                    entry_price = closes[i]
                    entry_idx = i
                    cur_mae = 0.0
                    cur_mfe = 0.0
                    funding_collected = 0.0
                    decision_id = gen_id()
                    paper_id = paper_trade_id(sym, times[i])
                    pos = PaperPosition(
                        symbol=sym,
                        bucket=policy["bucket"],
                        side="long",
                        entry_ts=ts_iso,
                        entry_price=float(entry_price),
                        entry_funding=float(funds[i]),
                        notional_usd=float(notional_usd),
                        stop_pct=float(stop_pct),
                        tp_pct=float(tp_pct),
                        max_hold_h=int(max_hold),
                        risk_usd=float(risk_usd),
                        decision_id=decision_id,
                        paper_id=paper_id,
                        status="open",
                    )
            else:
                # Update MAE/MFE
                bar_mae = (lows[i] - pos.entry_price) / pos.entry_price
                bar_mfe = (highs[i] - pos.entry_price) / pos.entry_price
                cur_mae = min(cur_mae, bar_mae)
                cur_mfe = max(cur_mfe, bar_mfe)
                # Accrue funding for this bar (long, if fund<0, receive)
                if funds[i] < 0:
                    funding_collected += abs(funds[i]) * pos.notional_usd

                hold_bars = i - entry_idx
                tp_price = pos.entry_price * (1 + tp_pct)
                sl_price = pos.entry_price * (1 - stop_pct)

                exit_now = False
                exit_reason = ""
                exit_price = closes[i]

                if lows[i] <= sl_price:
                    exit_now = True
                    exit_reason = "stop_loss"
                    exit_price = sl_price
                elif highs[i] >= tp_price:
                    exit_now = True
                    exit_reason = "take_profit"
                    exit_price = tp_price
                elif hold_bars >= max_hold:
                    exit_now = True
                    exit_reason = "max_hold"

                if exit_now:
                    net_pnl_usd, is_loss = _close_position(
                        pos=pos, exit_price=exit_price, exit_reason=exit_reason,
                        cur_mae=cur_mae, cur_mfe=cur_mfe, hold_bars=hold_bars,
                        funding_collected=funding_collected, cost_usd_per_trade=cost_usd_per_trade,
                        ts_iso=ts_iso, ts_date=ts_date,
                    )
                    cum_pnl += net_pnl_usd
                    daily_pnl[ts_date] = daily_pnl.get(ts_date, 0) + net_pnl_usd

                    # Consec loss tracking
                    if is_loss:
                        consec_loss += 1
                        if consec_loss >= CONSEC_LOSS_HALT:
                            halt_until[sym] = (times[i] + pd.Timedelta(hours=24)).isoformat()
                            print(f"  [{sym}] consec loss halt: {consec_loss} losses, halt until {halt_until[sym]}")
                            consec_loss = 0
                    else:
                        consec_loss = 0

                    print(f"  [{sym} {policy['bucket']}] CLOSED {exit_reason}: entry={pos.entry_price:.2f} exit={exit_price:.2f}  net=${net_pnl_usd:+.2f} (cum=${cum_pnl:+.2f})  hold={hold_bars}h  fund=${funding_collected:+.4f}")
                    in_trade = False
                    pos = None

    print(f"\nTotal closed: {sum(1 for p in load_existing_positions() if p.get('status') == 'closed')}  cum PnL: ${cum_pnl:+.2f}")


